CREATE OR REPLACE FUNCTION private.normalize_moderation_text(_value text)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path = pg_catalog
AS $$
  SELECT translate(
    translate(
      lower(coalesce(_value, '')),
      'áàâãäéèêëíìîïóòôõöúùûüçñ',
      'aaaaaeeeeiiiiooooouuuucn'
    ),
    '0134578@$!+',
    'oieastbasit'
  );
$$;

CREATE OR REPLACE FUNCTION private.moderation_term_pattern(_term text)
RETURNS text
LANGUAGE sql
IMMUTABLE
STRICT
SET search_path = pg_catalog
AS $$
  SELECT '(^|[^a-z0-9])'
    || string_agg(
      substr(_term, positions.position_number, 1) || '+',
      '[^a-z0-9]*'
      ORDER BY positions.position_number
    )
    || '([^a-z0-9]|$)'
  FROM generate_series(1, char_length(_term)) AS positions(position_number);
$$;

CREATE OR REPLACE FUNCTION private.blocked_content_category(
  _value text,
  _context text DEFAULT 'chat'
)
RETURNS text
LANGUAGE sql
STABLE
SET search_path = pg_catalog, private
AS $$
  WITH normalized AS (
    SELECT
      private.normalize_moderation_text(_value) AS spaced,
      regexp_replace(private.normalize_moderation_text(_value), '[^a-z0-9]', '', 'g') AS compact
  )
  SELECT terms.category
  FROM private.content_moderation_terms AS terms
  CROSS JOIN normalized
  WHERE terms.active
    AND (
      normalized.spaced ~ private.moderation_term_pattern(terms.term)
      OR (
        _context = 'username'
        AND terms.block_in_username_compounds
        AND position(terms.term IN normalized.compact) > 0
      )
    )
  ORDER BY
    CASE terms.category
      WHEN 'racism' THEN 1
      WHEN 'homophobia' THEN 2
      WHEN 'transphobia' THEN 3
      WHEN 'sexual' THEN 4
      ELSE 5
    END,
    char_length(terms.term) DESC
  LIMIT 1;
$$;

