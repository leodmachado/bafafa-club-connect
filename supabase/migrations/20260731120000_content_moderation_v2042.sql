CREATE OR REPLACE FUNCTION public.check_content_allowed(
  _value text,
  _context text DEFAULT 'chat'
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, private
AS $$
DECLARE
  v_category text;
BEGIN
  IF _context NOT IN ('display_name', 'username', 'chat') THEN
    RAISE EXCEPTION 'Contexto de moderação inválido.';
  END IF;

  IF char_length(coalesce(_value, '')) > 1200 THEN
    RETURN jsonb_build_object('allowed', false);
  END IF;

  v_category := private.blocked_content_category(_value, _context);
  RETURN jsonb_build_object('allowed', v_category IS NULL);
END;
$$;

REVOKE ALL ON FUNCTION public.check_content_allowed(text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.check_content_allowed(text, text) TO anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION private.tg_reject_sensitive_content()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, private
AS $$
BEGIN
  IF TG_TABLE_SCHEMA = 'public' AND TG_TABLE_NAME = 'profiles' THEN
    IF private.blocked_content_category(NEW.display_name, 'display_name') IS NOT NULL THEN
      RAISE EXCEPTION 'Esse nome não pode ser usado. Escolha um nome sem ofensas ou discriminação.';
    END IF;
    IF NEW.username IS NOT NULL
       AND private.blocked_content_category(NEW.username, 'username') IS NOT NULL THEN
      RAISE EXCEPTION 'Esse nome de usuário não pode ser usado. Escolha outro sem ofensas ou discriminação.';
    END IF;
  ELSIF TG_TABLE_SCHEMA = 'public' AND TG_TABLE_NAME IN (
    'event_chat_messages', 'private_chat_messages'
  ) THEN
    IF private.blocked_content_category(NEW.body, 'chat') IS NOT NULL THEN
      RAISE EXCEPTION 'Essa mensagem não segue as regras da comunidade. Ajuste o texto e tente de novo.';
    END IF;
  ELSIF TG_TABLE_SCHEMA = 'public' AND TG_TABLE_NAME = 'salve_requests' THEN
    IF NEW.opener IS NOT NULL
       AND private.blocked_content_category(NEW.opener, 'chat') IS NOT NULL THEN
      RAISE EXCEPTION 'Esse salve não segue as regras da comunidade. Ajuste o texto e tente de novo.';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION private.tg_reject_sensitive_content() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION private.tg_reject_sensitive_content() TO service_role;

